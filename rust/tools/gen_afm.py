import re, sys, os
base = os.path.join(sys.argv[1], "matplotlib", "mpl-data", "fonts", "afm")

def load(fn):
    by_code, by_name = {}, {}
    for line in open(os.path.join(base, fn), encoding="latin-1"):
        m = re.match(r"C\s+(-?\d+)\s*;\s*WX\s+(\d+)\s*;\s*N\s+(\S+)\s*;", line)
        if m:
            code, wx, name = int(m.group(1)), int(m.group(2)), m.group(3)
            by_name[name] = wx
            if code >= 0:
                by_code[code] = wx
    return by_code, by_name

out = ["// GENERATED by rust/tools/gen_afm.py from the Adobe Helvetica AFM files; do not edit by hand.", ""]
for tag, fn in (("HELVETICA", "phvr8a.afm"), ("HELVETICA_BOLD", "phvb8a.afm")):
    code, name = load(fn)
    code = dict(code)
    code[39] = name["quotesingle"]  # WinAnsi 39 is the straight quote, StandardEncoding has quoteright there
    code[96] = name["grave"]
    arr = [code[c] for c in range(32, 127)]
    out.append(f"/// Advance widths (1/1000 em) of ASCII 32..=126.")
    out.append(f"pub const {tag}: [u16; 95] = [{', '.join(map(str, arr))}];")
    extras = {"periodcentered": 0xB7, "degree": 0xB0, "mu": 0xB5, "endash": 0x96, "emdash": 0x97, "ellipsis": 0x85, "bullet": 0x95, "plusminus": 0xB1, "multiply": 0xD7}
    ex = [(ch, name[n]) for n, ch in extras.items() if n in name]
    out.append(f"/// Widths of a few WinAnsi characters outside ASCII: (code, width).")
    out.append(f"pub const {tag}_EXTRA: [(u8, u16); {len(ex)}] = [{', '.join(f'({c:#04x}, {w})' for c, w in ex)}];")
    out.append("")
print("\n".join(out))
